"""Mod Source / Mod Destination enum tables, from the Prophet 12 Module
Operation Manual's "Appendix A: Modulation Sources" and "Appendix B:
Modulation Destinations" (MIDI Implementation chapter, pages 91-93 of the
v1.2 PDF). Used to turn the "Mod N Source/Destination", "LFO N Destination"
and "Envelope 3/4 Destination" NRPN parameters -- which the main parameter
table only describes as "(see table of modulation sources/destinations and
values)" with no inline enum -- into proper dropdowns instead of raw knobs.

Each entry is (label, category); category drives the tree-style grouped
dropdown (see Source12/CategorizedCombo). The on-wire NRPN value for item i
is simply i (its position in this list) -- same index-is-value convention
used by every other enum in this project.

NOTE: the manual itself prints two duplicate destination VALUES ("LFO 1
Amount" printed as 59, same as "LFO 4 Freq"; "Mod 7 Amount" printed as 88,
same as "Mod 6 Amount") -- single off-by-one typos (every entry after each
duplicate already continues the correct +1 sequence either way), not a real
hardware quirk. Position-based indexing here sidesteps the typo entirely.
"""

