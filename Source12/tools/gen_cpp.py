import json, re

params = json.load(open('parameters.json'))
byte_offset_map = json.load(open('byte_offset_map.json')) if __import__('os').path.exists('byte_offset_map.json') else {}

SECTION_TITLES = {
    'OSC1': 'Oscillator 1', 'OSC2': 'Oscillator 2', 'OSC3': 'Oscillator 3', 'OSC4': 'Oscillator 4',
    'CHARACTER': 'Character', 'LPF': 'Low-Pass Filter', 'LPF_ENV': 'LPF Envelope', 'HPF': 'High-Pass Filter',
    'FEEDBACK': 'Feedback', 'VCA_MISC': 'Amp / Mix', 'VCA_ENV': 'VCA Envelope',
    'ENV3': 'Envelope 3', 'ENV4': 'Envelope 4',
    'LFO1': 'LFO 1', 'LFO2': 'LFO 2', 'LFO3': 'LFO 3', 'LFO4': 'LFO 4',
    'DELAY1': 'Delay 1', 'DELAY2': 'Delay 2', 'DELAY3': 'Delay 3', 'DELAY4': 'Delay 4',
    'MODMATRIX': 'Modulation Matrix', 'UNISON': 'Unison', 'GLOBAL': 'Global', 'GLIDE': 'Glide', 'ARP': 'Arpeggiator',
}
SECTION_ORDER = ['OSC1','OSC2','OSC3','OSC4','CHARACTER','LPF','LPF_ENV','HPF','FEEDBACK',
                  'VCA_MISC','VCA_ENV','ENV3','ENV4','LFO1','LFO2','LFO3','LFO4',
                  'DELAY1','DELAY2','DELAY3','DELAY4','MODMATRIX','UNISON','GLIDE','ARP','GLOBAL']

def slugify(name, seen):
    s = re.sub(r'[^a-zA-Z0-9]+', '_', name).strip('_').lower()
    base = s
    i = 2
    while s in seen:
        s = f"{base}_{i}"
        i += 1
    seen.add(s)
    return s

def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')

seen_ids = set()
for p in params:
    p['id'] = slugify(p['name'], seen_ids)

# ---- Parameters.h ----
h = []
h.append('// AUTO-GENERATED by build_params.py from the Prophet 12 Module Operation')
h.append('// Manual MIDI Implementation chapter (NRPN program-parameter table).')
h.append('// Do not hand-edit -- regenerate from parameters.json instead.')
h.append('#pragma once')
h.append('#include <juce_audio_processors/juce_audio_processors.h>')
h.append('')
h.append('namespace p12 {')
h.append('')
h.append('enum class ParamType { Knob, Toggle, Enum };')
h.append('')
h.append('struct ParamDef')
h.append('{')
h.append('    int nrpnA;')
h.append('    int nrpnB;')
h.append('    const char* id;')
h.append('    const char* name;')
h.append('    const char* section;')
h.append('    int minValue;')
h.append('    int maxValue;')
h.append('    ParamType type;')
h.append('    int firstOptionIndex;  // index into kOptionStrings/kOptionCategories, or -1')
h.append('    int numOptions;')
h.append('    bool treeCategorized;  // show as a grouped/tree dropdown, not a flat list')
h.append('    int dumpByteOffset;  // offset into the unpacked Program/Edit Buffer Dump, or -1 if unmapped')
h.append('    int dumpByteOffsetMirror;  // second copy (Split Point/A-B Mode only), or -1')
h.append('};')
h.append('')
h.append(f'constexpr int kNumParams = {len(params)};')
h.append('extern const ParamDef kParams[kNumParams];')
h.append('extern const char* const kOptionStrings[];')
h.append('extern const char* const kOptionCategories[];  // parallel to kOptionStrings, "" if uncategorized')
h.append('extern const int kNumOptionStrings;')
h.append('')
h.append('struct SectionDef { const char* id; const char* title; };')
h.append(f'constexpr int kNumSections = {len(SECTION_ORDER)};')
h.append('extern const SectionDef kSections[kNumSections];')
h.append('')
h.append('juce::AudioProcessorValueTreeState::ParameterLayout createParameterLayout();')
h.append('')
h.append('// NRPN (Layer A or Layer B) -> parameter index. Built once at startup.')
h.append('const std::map<int, int>& nrpnToParamIndex();')
h.append('')
h.append('}  // namespace p12')
open('Parameters.h', 'w').write('\n'.join(h) + '\n')

# ---- option strings flat table ----
option_strings = []
option_categories = []
for p in params:
    if p['options']:
        p['_optStart'] = len(option_strings)
        option_strings.extend(p['options'])
        cats = p.get('categories')
        if cats:
            option_categories.extend(cats)
        else:
            option_categories.extend([''] * len(p['options']))
        p['_optCount'] = len(p['options'])
    else:
        p['_optStart'] = -1
        p['_optCount'] = 0

# ---- Parameters.cpp ----
c = []
c.append('// AUTO-GENERATED by build_params.py. Do not hand-edit.')
c.append('#include "Parameters.h"')
c.append('')
c.append('namespace p12 {')
c.append('')
c.append('const char* const kOptionStrings[] = {')
for o in option_strings:
    c.append(f'    "{esc(o)}",')
c.append('};')
c.append('const char* const kOptionCategories[] = {')
for cat in option_categories:
    c.append(f'    "{esc(cat)}",')
c.append('};')
c.append(f'const int kNumOptionStrings = {len(option_strings)};')
c.append('')
c.append('const ParamDef kParams[kNumParams] = {')
type_name = {'knob': 'ParamType::Knob', 'toggle': 'ParamType::Toggle', 'enum': 'ParamType::Enum'}
for p in params:
    bm = byte_offset_map.get(p['name'], {})
    off = bm.get('byte_offset', -1)
    offMirror = bm.get('byte_offset_mirror', -1)
    c.append('    { %d, %d, "%s", "%s", "%s", %d, %d, %s, %d, %d, %s, %d, %d },' % (
        p['nrpnA'], p['nrpnB'] if p['nrpnB'] is not None else -1,
        p['id'], esc(p['name']), p['section'], p['min'], p['max'],
        type_name[p['type']], p['_optStart'], p['_optCount'],
        'true' if p.get('categories') else 'false', off, offMirror))
c.append('};')
c.append('')
c.append('const SectionDef kSections[kNumSections] = {')
for sec in SECTION_ORDER:
    c.append(f'    {{ "{sec}", "{esc(SECTION_TITLES[sec])}" }},')
c.append('};')
c.append('')
c.append('juce::AudioProcessorValueTreeState::ParameterLayout createParameterLayout()')
c.append('{')
c.append('    juce::AudioProcessorValueTreeState::ParameterLayout layout;')
c.append('    for (const auto& def : kParams)')
c.append('    {')
c.append('        if (def.type == ParamType::Toggle)')
c.append('        {')
c.append('            layout.add(std::make_unique<juce::AudioParameterBool>(')
c.append('                juce::ParameterID(def.id, 1), def.name, false));')
c.append('        }')
c.append('        else if (def.type == ParamType::Enum)')
c.append('        {')
c.append('            juce::StringArray choices;')
c.append('            for (int i = 0; i < def.numOptions; ++i)')
c.append('                choices.add(kOptionStrings[def.firstOptionIndex + i]);')
c.append('            if (choices.isEmpty())')
c.append('                choices.add("Off");')
c.append('            layout.add(std::make_unique<juce::AudioParameterChoice>(')
c.append('                juce::ParameterID(def.id, 1), def.name, choices, 0));')
c.append('        }')
c.append('        else')
c.append('        {')
c.append('            layout.add(std::make_unique<juce::AudioParameterInt>(')
c.append('                juce::ParameterID(def.id, 1), def.name, def.minValue, def.maxValue, def.minValue));')
c.append('        }')
c.append('    }')
c.append('    return layout;')
c.append('}')
c.append('')
c.append('const std::map<int, int>& nrpnToParamIndex()')
c.append('{')
c.append('    static const std::map<int, int> table = [] {')
c.append('        std::map<int, int> m;')
c.append('        for (int i = 0; i < kNumParams; ++i)')
c.append('        {')
c.append('            m[kParams[i].nrpnA] = i;')
c.append('            if (kParams[i].nrpnB >= 0)')
c.append('                m[kParams[i].nrpnB] = i;')
c.append('        }')
c.append('        return m;')
c.append('    }();')
c.append('    return table;')
c.append('}')
c.append('')
c.append('}  // namespace p12')
open('Parameters.cpp', 'w').write('\n'.join(c) + '\n')

# ---- Sections -> param id list (for the editor) ----
sections_json = {sec: [p['id'] for p in params if p['section'] == sec] for sec in SECTION_ORDER}
json.dump(sections_json, open('sections.json', 'w'), indent=2)

print('wrote Parameters.h, Parameters.cpp, sections.json')
print('num params', len(params), 'num options', len(option_strings))
