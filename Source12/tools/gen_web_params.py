"""Generate ui/params.js from Parameters.cpp (the codegen'd C++ table).

Run from Source12/:  python tools/gen_web_params.py
Re-run whenever Parameters.cpp is regenerated (gen_cpp.py) so the web UI
stays in sync with the plugin's parameters.
"""
import json, re, sys, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "Parameters.cpp").read_text(encoding="utf-8")


def string_array(name):
    m = re.search(name + r"\[\]\s*=\s*\{(.*?)\n\};", src, re.S)
    return re.findall(r'"((?:[^"\\]|\\.)*)"', m.group(1)) if m else None


options = string_array("kOptionStrings") or []
categories = string_array("kOptionCategories") or [""] * len(options)

row = re.compile(r'\{\s*(-?\d+),\s*(-?\d+),\s*"([^"]+)",\s*"([^"]+)",\s*"([^"]+)",\s*(-?\d+),\s*(-?\d+),\s*'
                 r'ParamType::(\w+),\s*(-?\d+),\s*(-?\d+)[^}]*\}')
table = re.search(r"kParams\[kNumParams\]\s*=\s*\{(.*?)\n\};", src, re.S).group(1)

params = []
for m in row.finditer(table):
    nA, nB, pid, name, sec, lo, hi, typ, first, num = m.groups()
    p = {"id": pid, "name": name, "section": sec, "min": int(lo), "max": int(hi), "type": typ.lower()}
    f, n = int(first), int(num)
    if f >= 0 and n > 0:
        p["options"] = options[f:f + n]
        if typ == "Enum":
            # The APVTS Choice param only holds len(options) values, so the UI
            # must not offer more than that (see CONTEXT.md re lfo_1_shape).
            p["max"] = p["min"] + n - 1
        cats = categories[f:f + n]
        if any(cats):
            p["categories"] = cats
    elif typ == "Enum":
        p["options"] = ["Off"]
    params.append(p)

sections = re.findall(r'\{\s*"([A-Z0-9_]+)",\s*"([^"]+)"\s*\}',
                      re.search(r"kSections\[kNumSections\]\s*=\s*\{(.*?)\};", src, re.S).group(1))

header = root / "Parameters.h"
expected = int(re.search(r"kNumParams\s*=\s*(\d+)", header.read_text(encoding="utf-8")).group(1)) \
    if header.exists() else len(params)

out = "// AUTO-GENERATED by tools/gen_web_params.py from Parameters.cpp. Do not hand-edit.\n"
out += "window.SEER_PARAMS = " + json.dumps(params, indent=1) + ";\n"
out += "window.SEER_SECTIONS = " + json.dumps([{"id": a, "title": b} for a, b in sections]) + ";\n"
(root / "ui" / "params.js").write_text(out, encoding="utf-8")
print(f"wrote {len(params)} params, {len(sections)} sections")
if len(params) != expected:
    sys.exit(f"expected {expected} params, parsed {len(params)}")
